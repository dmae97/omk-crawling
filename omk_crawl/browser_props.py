# Deterministic LCG: identical to browser_props._Rng, so the page reproduces
# the same stream the planner used without shipping a lookup table.
_NOISE_JS = """
  const makeNoise = (seed) => {
    let s = seed >>> 0;
    return () => { s = (Math.imul(s, 1664525) + 1013904223) >>> 0; return s / 4294967296; };
  };
""".strip("\n")

_CANVAS_NOISE_JS = """
  const canvasNoise = makeNoise(CANVAS_SEED);
  const _getImageData = CanvasRenderingContext2D.prototype.getImageData;
  define(CanvasRenderingContext2D.prototype, 'getImageData',
    native(function getImageData(...args) {
      const data = _getImageData.apply(this, args);
      // Perturb only the low bit of a sparse subset: invisible to a human,
      // but stable for this seed — so the canvas hash does not drift between
      // visits to the same site.
      for (let i = 0; i < data.data.length; i += 4) {
        if (canvasNoise() > 0.92) { data.data[i] = data.data[i] ^ 1; }
      }
      return data;
    }, 'getImageData', 1));
""".strip("\n")

_AUDIO_NOISE_JS = """
  const audioNoise = makeNoise(AUDIO_SEED);
  const _getChannelData = AudioBuffer.prototype.getChannelData;
  define(AudioBuffer.prototype, 'getChannelData',
    native(function getChannelData(...args) {
      const data = _getChannelData.apply(this, args);
      for (let i = 0; i < data.length; i += 977) {
        data[i] = data[i] + (audioNoise() - 0.5) * 1e-7;
      }
      return data;
    }, 'getChannelData', 1));
""".strip("\n")


# The helper installer. cdp.py imports this exact constant rather than keeping
# its own copy, so the two modules cannot drift apart. Nothing is attached to
# `window`: every helper stays in the enclosing IIFE closure, because a global
# like `__native` would be one more unique token for a detector to key on.
BOOTSTRAP = """
  const _nativeSrc = Function.prototype.toString;
  const _origSrc = new WeakMap();
  const native = (fn, name, arity) => {
    const wrapped = function (...args) { return fn.apply(this, args); };
    Object.defineProperty(wrapped, 'name',
      { value: name || fn.name || '', configurable: true });
    Object.defineProperty(wrapped, 'length',
      { value: arity === undefined ? (fn.length || 0) : arity, configurable: true });
    _origSrc.set(wrapped, 'function ' + (name || fn.name || '') + '() { [native code] }');
    return wrapped;
  };
  const nativeToString = function toString() {
    const stored = _origSrc.get(this);
    return stored !== undefined ? stored : _nativeSrc.call(this);
  };
  _origSrc.set(nativeToString, 'function toString() { [native code] }');
  Object.defineProperty(Function.prototype, 'toString',
    { value: nativeToString, writable: true, configurable: true });
  const define = (obj, prop, value) => Object.defineProperty(obj, prop, {
    value, writable: true, enumerable: false, configurable: true,
  });
""".strip("\n")


def props_body(spec: BrowserPropertySpec) -> str:
    """The property assignments only — for composition inside a shared IIFE.

    Depends on the ``native()`` and ``define()`` helpers from :data:`BOOTSTRAP`
    being in scope. Use :func:`spoof_script` for a self-contained script.
    """
    return _spoof_body(spec)


def spoof_script(spec: BrowserPropertySpec) -> str:
    """Self-contained property-spoofing init script for ``spec``.

    Byte-identical for identical specs — the temporal-stability requirement
    (FP-Inconsistent's second axis): a device that resamples its canvas hash on
    every visit is as suspicious as one whose headers rotate.
    """
    return "(() => {\n  'use strict';\n" + BOOTSTRAP + "\n\n" + _spoof_body(spec) + "\n})();"


def _spoof_body(spec: BrowserPropertySpec) -> str:
    """The property assignments, shared by both composition modes."""
    return f"""{_NOISE_JS}

  const NAV = Navigator.prototype;
  const SCREEN = Screen.prototype;

  define(NAV, 'platform', {spec.platform!r});
  define(NAV, 'languages', {_js_value(spec.languages)});
  define(NAV, 'language', {_js_value(spec.languages[0]) if spec.languages else "''"});
  define(NAV, 'hardwareConcurrency', {spec.hardware_concurrency});
  define(NAV, 'deviceMemory', {spec.device_memory});
  define(NAV, 'maxTouchPoints', {spec.max_touch_points});
  define(NAV, 'webdriver', false);

  // Intl must agree with the timezone the profile claims, or the mismatch is
  // itself the signal.
  const TZ = {spec.timezone!r};
  const _resolved = Intl.DateTimeFormat.prototype.resolvedOptions;
  define(Intl.DateTimeFormat.prototype, 'resolvedOptions',
    native(function resolvedOptions(...args) {{
      const opts = _resolved.apply(this, args);
      opts.timeZone = TZ;
      return opts;
    }}, 'resolvedOptions', 0));

  define(SCREEN, 'width', {spec.screen[0]});
  define(SCREEN, 'height', {spec.screen[1]});
  define(SCREEN, 'availWidth', {spec.avail[0]});
  define(SCREEN, 'availHeight', {spec.avail[1]});
  define(SCREEN, 'colorDepth', 24);
  define(SCREEN, 'pixelDepth', 24);
  define(window, 'devicePixelRatio', {spec.device_pixel_ratio});

  // Outer dimensions must be non-zero and never smaller than the viewport.
  // Headless windows report zero here, which is a direct tell — and deriving
  // them from the profile's own screen keeps the pair self-consistent.
  define(window, 'outerWidth', {spec.screen[0]});
  define(window, 'outerHeight', {spec.screen[1]});

  define(NAV, 'connection', {{
    effectiveType: '4g', rtt: 50, downlink: 10, saveData: false,
  }});

{_PLUGINS_JS}

  // WebGL must name hardware plausible for the claimed OS; a software renderer
  // is a GPU-less-host tell.
  const _getParameter = WebGLRenderingContext.prototype.getParameter;
  define(WebGLRenderingContext.prototype, 'getParameter',
    native(function getParameter(p) {{
      if (p === 37445) return {spec.webgl.unmasked_vendor!r};
      if (p === 37446) return {spec.webgl.unmasked_renderer!r};
      return _getParameter.apply(this, [p]);
    }}, 'getParameter', 1));

{_CANVAS_NOISE_JS.replace('CANVAS_SEED', str(spec.canvas_noise))}

{_AUDIO_NOISE_JS.replace('AUDIO_SEED', str(spec.audio_noise))}
""".strip("\n")


def probe_script() -> str:
    """JS expression returning the observation surface for :func:`audit_props`.

    Keys match :func:`audit_props`'s expected mapping, so a live
    ``page.evaluate(probe_script())`` and an offline dict exercise the same
    audit code.
    """
    return """(() => (() => { try {
    const canvas = document.createElement('canvas');
    const gl = canvas.getContext('webgl');
    let renderer = null;
    if (gl) {
      const dbg = gl.getExtension('WEBGL_debug_renderer_info');
      renderer = dbg ? String(gl.getParameter(dbg.UNMASKED_RENDERER_WEBGL)) : null;
    }
    return {
      platform: navigator.platform,
      languages: Array.from(navigator.languages || []),
      timezone: Intl.DateTimeFormat().resolvedOptions().timeZone,
      screen: [screen.width, screen.height],
      avail: [screen.availWidth, screen.availHeight],
      viewport: [window.innerWidth, window.innerHeight],
      device_pixel_ratio: window.devicePixelRatio,
      hardware_concurrency: navigator.hardwareConcurrency,
      device_memory: navigator.deviceMemory === undefined ? null : navigator.deviceMemory,
      max_touch_points: navigator.maxTouchPoints,
      webgl_renderer: renderer,
      pdf_viewer_enabled: typeof navigator.pdfViewerEnabled === 'boolean'
        ? navigator.pdfViewerEnabled : null,
      plugins_length: navigator.plugins ? navigator.plugins.length : 0,
    };
  } catch (e) { return { error: String(e) }; } })())"""


def audit_props(
    observed: Mapping[str, Any],
    profile: FingerprintProfile,
) -> list[str]:
    """Cross-layer audit of an observed JS surface against ``profile``.

    Only keys present in ``observed`` are judged, so partial probes (or a mock
    surface in tests) still produce a meaningful report. Rules are the ones
    real vendors check: locale/timezone agreement, platform agreement, the
    screen ≥ viewport invariant, and renderer plausibility for the OS.
    """
    issues: list[str] = []

    platform = observed.get("platform")
    expected_platform = _PLATFORM_STRINGS.get(profile.platform_os)
    if platform and expected_platform and platform != expected_platform:
        issues.append(
            f"navigator.platform {platform!r} != UA platform {profile.platform_os!r} "
            f"(expected {expected_platform!r})"
        )

    timezone = observed.get("timezone")
    if timezone and timezone != profile.timezone_id:
        issues.append(f"Intl timeZone {timezone!r} != profile {profile.timezone_id!r}")

    languages = observed.get("languages")
    if languages:
        first = str(languages[0]) if len(languages) else ""
        if first and first.lower() != profile.locale.lower():
            issues.append(f"navigator.languages[0] {first!r} != locale {profile.locale!r}")

    # screen must not be smaller than the viewport — a construction invariant
    # here, and a hard cross-check on any observation.
    screen = observed.get("screen")
    viewport = observed.get("viewport") or list(profile.viewport)
    if screen and viewport and len(screen) >= 2 and len(viewport) >= 2:
        if screen[0] < viewport[0] or screen[1] < viewport[1]:
            issues.append(f"screen {list(screen)} is smaller than viewport {list(viewport)}")

    avail = observed.get("avail")
    if avail and screen and len(avail) >= 2 and len(screen) >= 2:
        if avail[0] > screen[0] or avail[1] > screen[1]:
            issues.append(f"avail {list(avail)} exceeds screen {list(screen)}")

    renderer = observed.get("webgl_renderer")
    if renderer:
        expected = webgl_identity(profile)
        plausible = {w.unmasked_renderer for w in _WEBGL_BY_OS.get(profile.platform_os, ())}
        if renderer != expected.unmasked_renderer and renderer not in plausible:
            issues.append(
                f"WebGL renderer {renderer!r} is not plausible for {profile.platform_os} "
                f"(expected one of {sorted(plausible)})"
            )

    touch = observed.get("max_touch_points")
    if touch is not None:
        mobile = profile.mobile or profile.platform_os in ("Android", "iOS")
        if mobile and not touch:
            issues.append("mobile profile but navigator.maxTouchPoints is 0")
        if not mobile and touch:
            issues.append(f"desktop profile but navigator.maxTouchPoints is {touch}")

    dpr = observed.get("device_pixel_ratio")
    if (
        dpr is not None
        and profile.platform_os == "macOS"
        and dpr == 1
        and profile.viewport[0] > 1600
    ):
        issues.append("macOS with a large viewport but devicePixelRatio 1 is implausible")

    return issues
