"""Browser property spoofing — the JS object surface, derived from the profile.

v2.12 made HTTP headers coherent with the TLS target. That is only half the
story: the page can read `navigator.languages`, `Intl.DateTimeFormat().timeZone`,
`screen.width`, the unmasked WebGL renderer and a canvas hash, and compare all
of them against the headers it just received. Multi-layer web-agent
fingerprinting (arXiv:2606.30119) shows superficial stealth patches make an
agent *more* detectable when those layers disagree — so the fix is not "spoof
harder", it is "derive every value from the same identity".

Every value here comes from a :class:`~omk_crawl.fingerprint.FingerprintProfile`
plus an explicit seed. Two consequences worth stating:

  **Temporal stability.** Canvas and audio noise are generated by a seeded LCG
  embedded in the script, so the same ``(profile, seed)`` produces the *same*
  noise on every call. A machine that resamples its canvas hash on each visit is
  flagged by the over-time axis of FP-Inconsistent (arXiv:2406.07647); a machine
  that never changes is consistent with a real device.

  **Geometry sanity.** Screen dimensions are derived *from* the profile viewport
  rather than invented, so the invariant detectors actually check — screen must
  never be smaller than the viewport — holds by construction.

Not spoofed, and said plainly rather than faked: font enumeration, WebRTC
candidate surfaces, and TLS-level properties. Those need a browser build or
network layer, not an init script.
"""

