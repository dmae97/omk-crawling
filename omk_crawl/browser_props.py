def _seed_int(seed: int | str | bytes | None, profile_name: str) -> int:
    """Stable 64-bit seed (``None`` derives from the profile name)."""
    if seed is None:
        seed = profile_name
    if isinstance(seed, int):
        return seed & 0xFFFFFFFFFFFFFFFF
    if isinstance(seed, str):
        seed = seed.encode("utf-8")
    return int.from_bytes(hashlib.sha256(seed).digest()[:8], "big")


class _Rng:
    """Tiny deterministic PRNG — a fixed reference so Python and JS agree.

    Deliberately the same 32-bit LCG used by the emitted JavaScript, so the
    values chosen here are reproducible by the page without shipping a table.
    """

    def __init__(self, seed: int) -> None:
        self._state = seed & 0xFFFFFFFF

    def next(self) -> float:
        self._state = (self._state * 1664525 + 1013904223) & 0xFFFFFFFF
        return self._state / 0x100000000

    def pick(self, options: tuple[Any, ...]) -> Any:
        return options[int(self.next() * len(options)) % len(options)]

    def between(self, lo: float, hi: float) -> float:
        return lo + self.next() * (hi - lo)


def webgl_identity(profile: FingerprintProfile) -> WebglIdentity:
    """WebGL identity matching the profile's platform (deterministic)."""
    options = _WEBGL_BY_OS.get(profile.platform_os, _WEBGL_BY_OS["Linux"])
    return options[_seed_int(profile.name, profile.name) % len(options)]


@dataclass(frozen=True, slots=True)
class BrowserPropertySpec:
    """The full JS surface derived from one identity.

    Attributes:
        profile / seed: Inputs, kept so the spec is self-describing.
        platform: ``navigator.platform`` for the claimed OS.
        languages: ``navigator.languages`` — first entry is the profile locale.
        timezone: IANA zone from the profile.
        screen: ``(width, height)`` — always ≥ the profile viewport.
        avail: ``(width, height)`` minus taskbar/dock, still ≥ viewport.
        device_pixel_ratio: Plausible DPR for the OS class.
        hardware_concurrency / device_memory: Plausible mid-range values.
        max_touch_points: 0 on desktop identities, 5 on mobile ones.
        webgl: Renderer strings for the platform.
        canvas_noise / audio_noise: Seed of the deterministic perturbation
            applied to canvas/audio reads.
    """

    profile: str
    seed: int
    platform: str
    languages: tuple[str, ...]
    timezone: str
    screen: tuple[int, int]
    avail: tuple[int, int]
    device_pixel_ratio: float
    hardware_concurrency: int
    device_memory: int
    max_touch_points: int
    webgl: WebglIdentity
    canvas_noise: int
    audio_noise: int

    def to_dict(self) -> dict[str, Any]:
        """JSON-safe summary (no JS, safe for result metadata)."""
        return {
            "profile": self.profile,
            "platform": self.platform,
            "languages": list(self.languages),
            "timezone": self.timezone,
            "screen": list(self.screen),
            "avail": list(self.avail),
            "device_pixel_ratio": self.device_pixel_ratio,
            "hardware_concurrency": self.hardware_concurrency,
            "device_memory": self.device_memory,
            "max_touch_points": self.max_touch_points,
            "webgl_renderer": self.webgl.unmasked_renderer,
        }


def _languages_for(profile: FingerprintProfile) -> tuple[str, ...]:
    """Language list from ``Accept-Language`` so header and JS agree."""
    tags: list[str] = []
    for part in profile.accept_language.split(","):
        tag = part.split(";")[0].strip()
        if tag and tag not in tags:
            tags.append(tag)
    if profile.locale not in tags:
        tags.insert(0, profile.locale)
    return tuple(tags)


def property_spec(
    profile: FingerprintProfile,
    seed: int | str | bytes | None = None,
) -> BrowserPropertySpec:
    """Derive the full JS surface for ``profile`` (deterministic in ``seed``)."""
    seed_value = _seed_int(seed, profile.name)
    rng = _Rng(seed_value)

    viewport_w, viewport_h = profile.viewport
    # Browser chrome above the viewport, then a taskbar/dock away from the work
    # area. Both are bounded so `avail >= viewport` cannot fail.
    chrome_h = int(rng.between(96, 148))
    screen_h = viewport_h + chrome_h
    avail_h = max(viewport_h, screen_h - int(rng.between(32, 64)))

    dpr = rng.pick(_DPR_BY_OS.get(profile.platform_os, (1.0,)))
    # A macOS identity with a viewport too wide for a Retina panel would be a
    # contradiction; keep the panel ratio truthful regardless of what the pool
    # holds (defensive: the pool currently only offers 2.0).
    if profile.platform_os == "macOS" and dpr == 1.0 and viewport_w > 1600:
        dpr = 2.0

    mobile = profile.mobile or profile.platform_os in ("Android", "iOS")
    return BrowserPropertySpec(
        profile=profile.name,
        seed=seed_value,
        platform=_PLATFORM_STRINGS.get(profile.platform_os, "Linux x86_64"),
        languages=_languages_for(profile),
        timezone=profile.timezone_id,
        screen=(viewport_w, screen_h),
        avail=(viewport_w, avail_h),
        device_pixel_ratio=dpr,
        hardware_concurrency=int(rng.pick((4, 8, 8, 12, 16))),
        device_memory=int(rng.pick((8, 8, 16, 4))),
        max_touch_points=5 if mobile else 0,
        webgl=webgl_identity(profile),
        canvas_noise=(seed_value & 0x7FFFFFFF) or 1,
        audio_noise=((seed_value >> 13) & 0x7FFFFFFF) or 1,
    )


def _js_value(value: Any) -> str:
    """Render a Python value as a JS literal (JSON is a JS subset here)."""
    if value is True:
        return "true"
    if value is False:
        return "false"
    if isinstance(value, str):
        escaped = value.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n")
        return f"'{escaped}'"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, (tuple, list)):
        return "[" + ", ".join(_js_value(v) for v in value) + "]"
    raise TypeError(f"cannot render {type(value).__name__} as JS")


